// Traces a light-on-dark lettering bitmap into one SVG path and writes it as a TypeScript module.
// Usage: node scripts/trace-lettering.mjs <input.png> <output.ts> [threshold]
import { writeFileSync } from "node:fs";
import potrace from "potrace";

const [, , input, output, threshold = "175"] = process.argv;
if (!input || !output) {
  console.error("Usage: node scripts/trace-lettering.mjs <input.png> <output.ts> [threshold]");
  process.exit(1);
}

potrace.trace(
  input,
  {
    // Above mid-grey, so the anti-aliased slivers between touching letters stay background
    // instead of welding the letters together.
    threshold: Number(threshold),
    blackOnWhite: false,
    turdSize: 2,
    optTolerance: 0.4,
    alphaMax: 1,
  },
  (err, svg) => {
    if (err) throw err;
    const raw = svg.match(/ d="([^"]+)"/)[1];
    const points = [...raw.matchAll(/(-?\d+(?:\.\d+)?)[ ,](-?\d+(?:\.\d+)?)/g)].map((m) => [Number(m[1]), Number(m[2])]);
    const minX = Math.min(...points.map((p) => p[0]));
    const minY = Math.min(...points.map((p) => p[1]));
    const maxX = Math.max(...points.map((p) => p[0]));
    const maxY = Math.max(...points.map((p) => p[1]));
    // Crop to the ink: shift every absolute coordinate pair so the path starts at the origin.
    // potrace writes absolute M, L and C commands only, so every number pair is a point.
    const d = raw.replace(/(-?\d+(?:\.\d+)?)[ ,](-?\d+(?:\.\d+)?)/g, (_, x, y) => `${(Number(x) - minX).toFixed(1)} ${(Number(y) - minY).toFixed(1)}`);
    const width = Math.ceil(maxX - minX);
    const height = Math.ceil(maxY - minY);
    writeFileSync(
      output,
      `// Generated by scripts/trace-lettering.mjs from ${input.replace(/\\/g, "/")}; do not edit by hand.\nexport const nameMark = {\n  width: ${width},\n  height: ${height},\n  d: "${d.replace(/\s+/g, " ").trim()}",\n};\n`,
    );
    console.log(`${output}: ${width}×${height}, ${d.length} characters`);
  },
);
